const GENERIC_FAMILIES = new Set([
  'serif', 'sans-serif', 'monospace', 'cursive', 'fantasy', 'system-ui', 'ui-serif', 'ui-sans-serif',
  'ui-monospace', 'ui-rounded', 'math', 'emoji', 'fangsong', '-apple-system', 'blinkmacsystemfont',
]);

/**
 * CSS custom-property suffix for a token key: camelCase -> kebab-case; letters, digits, hyphens only.
 * @param {string} key
 * @returns {string}
 */
export function tokenName(key) {
  const k = String(key).replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[\s_]+/g, '-').toLowerCase();
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(k)) {
    throw new TokenError(`token key "${key}" cannot be used in a CSS custom property name (use letters, digits and hyphens)`);
  }
  return k;
}

function cssValue(value, where, unit = '', alwaysUnit = false) {
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new TokenError(`${where}: number must be finite`);
    return unit && (value !== 0 || alwaysUnit) ? `${value}${unit}` : String(value);
  }
  if (typeof value !== 'string') throw new TokenError(`${where}: expected a string or number`);
  const v = value.trim();
  if (v === '') throw new TokenError(`${where}: value is empty`);
  if (/[;{}\\<>\r\n]|\/\*|\*\//.test(v)) {
    throw new TokenError(`${where}: value contains characters that are not allowed in a token (; { } \\ < >, comments or line breaks)`);
  }
  let depth = 0;
  let quote = null;
  for (const ch of v) {
    if (quote) {
      if (ch === quote) quote = null;
    } else if (ch === '"' || ch === "'") {
      quote = ch;
    } else if (ch === '(') {
      depth += 1;
    } else if (ch === ')') {
      depth -= 1;
      if (depth < 0) break;
    }
  }
  if (quote || depth !== 0) throw new TokenError(`${where}: unbalanced quotes or parentheses`);
  return v;
}

function familyName(name, where) {
  const n = cssValue(name, where);
  if (/^(["']).*\1$/.test(n)) return n;
  if (GENERIC_FAMILIES.has(n.toLowerCase())) return n;
  if (/["']/.test(n)) throw new TokenError(`${where}: font family names must not contain quotes`);
  return `"${n}"`;
}

function fontStack(role, where) {
  const fallback = Array.isArray(role.fallback)
    ? role.fallback.map((f, i) => familyName(f, `${where}.fallback[${i}]`)).join(', ')
    : cssValue(role.fallback, `${where}.fallback`);
  return `${familyName(role.family, `${where}.family`)}, ${fallback}`;
}

/**
 * Google Fonts css2 URL for the font roles whose `source` mentions Google Fonts (null when none).
 * Nothing is fetched; the URL is a convenience for the page's <link>.
 * @param {object} typography
 * @returns {string|null}
 */
export function googleFontsUrl(typography) {
  const families = new Map();
  for (const role of ['display', 'text', 'mono']) {
    const r = typography?.[role];
    if (!r || typeof r.source !== 'string' || !/google fonts/i.test(r.source)) continue;
    const name = String(r.family).trim();
    const weights = families.get(name) ?? new Set();
    for (const w of Array.isArray(r.weights) ? r.weights : []) weights.add(w);
    families.set(name, weights);
  }
  if (families.size === 0) return null;
  const params = [...families].map(([name, set]) => {
    const list = [...set].filter((w) => Number.isInteger(w)).sort((a, b) => a - b);
    const fam = encodeURIComponent(name).replace(/%20/g, '+');
    const axis = list.length && !(list.length === 1 && list[0] === 400) ? `:wght@${list.join(';')}` : '';
    return `family=${fam}${axis}`;
  });
  return `https://fonts.googleapis.com/css2?${params.join('&')}&display=swap`;
}

function mapTokens(map, prefix, where, unit = '', alwaysUnit = false) {
  if (!map || typeof map !== 'object') return [];
  return Object.entries(map).map(([k, v]) => [`--${prefix}-${tokenName(k)}`, cssValue(v, `${where}.${k}`, unit, alwaysUnit)]);
}

function paletteDecls(palette, where) {
  return Object.entries(palette).map(([k, v]) => [`--color-${tokenName(k)}`, cssValue(v, `${where}.${k}`)]);
}

function block(selector, decls, indent = '') {
  return [`${indent}${selector} {`, ...decls.map(([n, v]) => `${indent}  ${n}: ${v};`), `${indent}}`].join('\n');
}

/**
 * Build tokens.css and theme.tailwind.css from a preset and measure its contrast pairs.
 * The preset should already satisfy schemas/preset.schema.json (see validatePreset); values
 * that would produce unsafe or broken CSS throw a TokenError.
 * @param {object} preset
 * @returns {{css: string, tailwindTheme: string, contrastResults: object[], ok: boolean,
 *   googleFontsUrl: string|null, warnings: string[]}}
 */
export function buildTokens(preset) {
  if (!preset || typeof preset !== 'object' || Array.isArray(preset)) throw new TokenError('preset must be a JSON object');
  const light = preset.color?.light;
  const dark = preset.color?.dark;
  if (!light || typeof light !== 'object') throw new TokenError('preset.color.light is required');
  if (dark !== undefined && (dark === null || typeof dark !== 'object')) throw new TokenError('preset.color.dark must be an object');
  const t = preset.typography ?? {};
  const motion = preset.motion ?? {};
  const name = String(preset.name ?? 'unnamed').replace(/[^a-z0-9-]/gi, '') || 'unnamed';
  const warnings = [];

  const fonts = ['display', 'text', 'mono'].filter((r) => t[r]).map((r) => [`--font-${r}`, fontStack(t[r], `typography.${r}`)]);
  const text = mapTokens(t.scale, 'text', 'typography.scale', 'px');
  const leading = mapTokens(t.lineHeights, 'leading', 'typography.lineHeights');
  const tracking = mapTokens(t.tracking, 'tracking', 'typography.tracking', 'em');
  const radius = mapTokens(preset.radius, 'radius', 'radius', 'px');
  const spacing = mapTokens(preset.space, 'spacing', 'space', 'px');
  const shadow = mapTokens(preset.shadow, 'shadow', 'shadow');
  const durations = mapTokens(motion.durations, 'duration', 'motion.durations', 'ms', true);
  const easings = mapTokens(motion.easings, 'ease', 'motion.easings');
  const lightColors = paletteDecls(light, 'color.light');
  const darkColors = dark ? paletteDecls(dark, 'color.dark') : [];

  if (dark) {
    const onlyLight = Object.keys(light).filter((k) => !(k in dark));
    const onlyDark = Object.keys(dark).filter((k) => !(k in light));
    if (onlyLight.length) warnings.push(`colour roles only in the light palette keep their light value in dark mode: ${onlyLight.join(', ')}`);
    if (onlyDark.length) warnings.push(`colour roles only in the dark palette are undefined in light mode: ${onlyDark.join(', ')}`);
  }
  if (!Array.isArray(preset.contrastPairs) || preset.contrastPairs.length === 0) warnings.push('no contrastPairs declared; nothing was measured');

  const fontsUrl = googleFontsUrl(t);
  const header = [
    `/* ${GENERATED_MARKER} from preset "${name}". Do not edit by hand: change the preset JSON and rebuild. */`,
    dark
      ? '/* Themes: light values apply on :root and [data-theme="light"]; dark values apply on [data-theme="dark"] and, unless <html data-theme="light">, when the OS prefers dark. data-theme also works on a section. */'
      : '/* Themes: this preset defines a light palette only. */',
    fontsUrl ? `/* Fonts are not fetched at build time. Google Fonts stylesheet for this preset: ${fontsUrl} */` : null,
  ].filter(Boolean);

  const rootDecls = [...fonts, ...text, ...leading, ...tracking, ...radius, ...spacing, ...shadow, ...durations, ...easings];
  const parts = [header.join('\n'), block(':root', rootDecls), block(':root,\n[data-theme="light"]', [['color-scheme', 'light'], ...lightColors])];
  if (dark) {
    const darkDecls = [['color-scheme', 'dark'], ...darkColors];
    parts.push(`@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', darkDecls, '  ')}\n}`);
    parts.push(block('[data-theme="dark"]', darkDecls));
  }
  if (durations.length) {
    parts.push(`@media (prefers-reduced-motion: reduce) {\n${block(':root', durations.map(([n]) => [n, '0.01ms']), '  ')}\n}`);
  }
  const css = `${parts.join('\n\n')}\n`;

  const lineHeightCompanions = Object.keys(t.scale ?? {})
    .filter((k) => t.lineHeights && Object.prototype.hasOwnProperty.call(t.lineHeights, k))
    .map((k) => [`--text-${tokenName(k)}--line-height`, cssValue(t.lineHeights[k], `typography.lineHeights.${k}`)]);
  const defaults = [];
  if (t.text) defaults.push(['--default-font-family', 'var(--font-text)']);
  if (t.mono) defaults.push(['--default-mono-font-family', 'var(--font-mono)']);
  const baseDuration = durations.find(([n]) => n === '--duration-base');
  const standardEase = easings.find(([n]) => n === '--ease-standard');
  if (baseDuration) defaults.push(['--default-transition-duration', baseDuration[1]]);
  if (standardEase) defaults.push(['--default-transition-timing-function', standardEase[1]]);
  const themeDecls = [...lightColors, ...fonts, ...text, ...lineHeightCompanions, ...leading, ...tracking, ...radius, ...spacing, ...shadow, ...easings, ...defaults];
  const tailwindTheme = [
    `/* ${GENERATED_MARKER} from preset "${name}". Do not edit by hand. */`,
    '/* Tailwind CSS v4: @import "tailwindcss"; then this file; then tokens.css, which supplies the runtime (dark mode) values for the same variable names. */',
    block('@theme', themeDecls),
    '',
  ].join('\n');

  const contrastResults = checkContrastPairs(preset);
  return { css, tailwindTheme, contrastResults, ok: contrastResults.every((r) => r.pass), googleFontsUrl: fontsUrl, warnings };
}

