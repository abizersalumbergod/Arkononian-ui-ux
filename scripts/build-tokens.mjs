const KAPPA = 24389 / 27;
const EPSILON = 216 / 24389;
const D50_WHITE = [0.3457 / 0.3585, 1, (1 - 0.3457 - 0.3585) / 0.3585];
// Matrices from CSS Color 4 (sample conversion code) and Ottosson's OKLab definition.
const XYZ65_TO_LIN_SRGB = [
  [12831 / 3959, -329 / 214, -1974 / 3959],
  [-851781 / 878810, 1648619 / 878810, 36519 / 878810],
  [705 / 12673, -2585 / 12673, 705 / 667],
];
const D50_TO_D65 = [
  [0.955473421488075, -0.02309845494876471, 0.06325924320057072],
  [-0.0283697093338637, 1.0099953980813041, 0.021041441191917323],
  [0.012314014864481998, -0.020507649298898964, 1.330365926242124],
];
const LIN_P3_TO_XYZ65 = [
  [608311 / 1250200, 189793 / 714400, 198249 / 1000160],
  [35783 / 156275, 247089 / 357200, 198249 / 2500400],
  [0, 32229 / 714400, 5220557 / 5000800],
];
const NAMED_COLORS = Object.freeze({ black: '#000000', white: '#ffffff', transparent: '#00000000' });
const WHITE = Object.freeze({ r: 1, g: 1, b: 1, a: 1 });
const BLACK = Object.freeze({ r: 0, g: 0, b: 0, a: 1 });
const GAMUT_TOLERANCE = 1e-5;

const mul = (m, v) => m.map((row) => row[0] * v[0] + row[1] * v[1] + row[2] * v[2]);
const clamp01 = (n) => Math.min(1, Math.max(0, n));

function srgbToLinear(c) {
  const a = Math.abs(c);
  const v = a <= 0.04045 ? a / 12.92 : ((a + 0.055) / 1.055) ** 2.4;
  return c < 0 ? -v : v;
}

function linearToSrgb(c) {
  const a = Math.abs(c);
  const v = a <= 0.0031308 ? a * 12.92 : 1.055 * a ** (1 / 2.4) - 0.055;
  return c < 0 ? -v : v;
}

function parseToken(tok, original) {
  if (/^none$/i.test(tok)) return { value: 0, unit: '' };
  const m = /^([+-]?(?:\d+\.?\d*|\.\d+)(?:e[+-]?\d+)?)(%|deg|rad|grad|turn)?$/i.exec(tok);
  if (!m) throw new Error(`cannot read component "${tok}" in "${original}"`);
  return { value: Number(m[1]), unit: (m[2] ?? '').toLowerCase() };
}

function scaled(t, full, original) {
  if (t.unit === '%') return (t.value / 100) * full;
  if (t.unit === '') return t.value;
  throw new Error(`unexpected unit "${t.unit}" in "${original}"`);
}

function hue(t, original) {
  switch (t.unit) {
    case '':
    case 'deg':
      return t.value;
    case 'rad':
      return (t.value * 180) / Math.PI;
    case 'grad':
      return t.value * 0.9;
    case 'turn':
      return t.value * 360;
    default:
      throw new Error(`invalid hue "${t.value}${t.unit}" in "${original}"`);
  }
}

function hslToSrgb(h, s, l) {
  const hh = ((h % 360) + 360) % 360;
  const f = (n) => {
    const k = (n + hh / 30) % 12;
    const a = s * Math.min(l, 1 - l);
    return l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1));
  };
  return [f(0), f(8), f(4)];
}

function labToXyzD50(L, a, b) {
  const fy = (L + 16) / 116;
  const fx = a / 500 + fy;
  const fz = fy - b / 200;
  const xyz = [
    fx ** 3 > EPSILON ? fx ** 3 : (116 * fx - 16) / KAPPA,
    L > KAPPA * EPSILON ? ((L + 16) / 116) ** 3 : L / KAPPA,
    fz ** 3 > EPSILON ? fz ** 3 : (116 * fz - 16) / KAPPA,
  ];
  return xyz.map((v, i) => v * D50_WHITE[i]);
}

function oklabToLinearSrgb(L, a, b) {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
}

function finish(encoded, alpha) {
  const outOfGamut = encoded.some((c) => c < -GAMUT_TOLERANCE || c > 1 + GAMUT_TOLERANCE);
  const [r, g, b] = encoded.map(clamp01);
  return { r, g, b, a: clamp01(alpha), outOfGamut };
}

const finishLinear = (linear, alpha) => finish(linear.map(linearToSrgb), alpha);

/**
 * Parse a CSS colour into gamma-encoded sRGB channels (0..1, clipped to the sRGB gamut) and alpha.
 * Supports #rgb/#rgba/#rrggbb/#rrggbbaa, rgb()/rgba(), hsl()/hsla() (comma and space syntax),
 * lab(), lch(), oklab(), oklch() and color(srgb | srgb-linear | display-p3 | xyz | xyz-d65 | xyz-d50),
 * plus the keywords black, white and transparent. Throws an Error for anything else
 * (relative colours, var(), calc(), other colour spaces).
 * @param {string} input
 * @returns {{r: number, g: number, b: number, a: number, outOfGamut: boolean}}
 */
export function parseColor(input) {
  if (typeof input !== 'string') throw new Error('colour must be a string');
  const original = input.trim();
  const text = original.toLowerCase();
  if (Object.prototype.hasOwnProperty.call(NAMED_COLORS, text)) return parseColor(NAMED_COLORS[text]);
  if (text.startsWith('#')) {
    const hex = text.slice(1);
    if (!/^(?:[0-9a-f]{3,4}|[0-9a-f]{6}|[0-9a-f]{8})$/.test(hex)) throw new Error(`invalid hex colour "${original}"`);
    const full = hex.length <= 4 ? [...hex].map((c) => c + c).join('') : hex;
    const n = (i) => parseInt(full.slice(i, i + 2), 16) / 255;
    return finish([n(0), n(2), n(4)], full.length === 8 ? n(6) : 1);
  }
  const fn = /^([a-z][a-z0-9-]*)\((.*)\)$/s.exec(text);
  if (!fn) throw new Error(`unsupported colour syntax "${original}"`);
  const [, name, rawInner] = fn;
  const inner = rawInner.trim();
  if (inner.includes('(') || /\bfrom\b/.test(inner)) {
    throw new Error(`relative colours, var(), calc() and nested functions cannot be measured ("${original}")`);
  }
  let parts;
  let alphaText = null;
  if (inner.includes(',')) {
    parts = inner.split(',').map((s) => s.trim());
    if (parts.length === 4) alphaText = parts.pop();
  } else {
    const slash = inner.split('/');
    if (slash.length > 2) throw new Error(`too many "/" in "${original}"`);
    parts = slash[0].trim().split(/\s+/).filter(Boolean);
    if (slash.length === 2) alphaText = slash[1].trim();
  }
  const alpha = alphaText === null ? 1 : scaled(parseToken(alphaText, original), 1, original);
  if (name === 'color') {
    const [space, ...rest] = parts;
    if (rest.length !== 3) throw new Error(`color() needs a colour space and 3 components ("${original}")`);
    const v = rest.map((tok) => scaled(parseToken(tok, original), 1, original));
    switch (space) {
      case 'srgb':
        return finish(v, alpha);
      case 'srgb-linear':
        return finishLinear(v, alpha);
      case 'display-p3':
        return finishLinear(mul(XYZ65_TO_LIN_SRGB, mul(LIN_P3_TO_XYZ65, v.map(srgbToLinear))), alpha);
      case 'xyz':
      case 'xyz-d65':
        return finishLinear(mul(XYZ65_TO_LIN_SRGB, v), alpha);
      case 'xyz-d50':
        return finishLinear(mul(XYZ65_TO_LIN_SRGB, mul(D50_TO_D65, v)), alpha);
      default:
        throw new Error(`colour space "${space}" is not supported for contrast checks ("${original}")`);
    }
  }
  if (parts.length !== 3) throw new Error(`expected 3 colour components in "${original}"`);
  const t = parts.map((tok) => parseToken(tok, original));
  switch (name) {
    case 'rgb':
    case 'rgba':
      return finish(t.map((c) => scaled(c, 255, original) / 255), alpha);
    case 'hsl':
    case 'hsla': {
      const pct = (c) => {
        if (c.unit !== '%' && c.unit !== '') throw new Error(`invalid saturation/lightness in "${original}"`);
        return clamp01(c.value / 100);
      };
      return finish(hslToSrgb(hue(t[0], original), pct(t[1]), pct(t[2])), alpha);
    }
    case 'lab':
    case 'lch': {
      const L = scaled(t[0], 100, original);
      let a;
      let b;
      if (name === 'lab') {
        a = scaled(t[1], 125, original);
        b = scaled(t[2], 125, original);
      } else {
        const C = scaled(t[1], 150, original);
        const H = (hue(t[2], original) * Math.PI) / 180;
        a = C * Math.cos(H);
        b = C * Math.sin(H);
      }
      return finishLinear(mul(XYZ65_TO_LIN_SRGB, mul(D50_TO_D65, labToXyzD50(L, a, b))), alpha);
    }
    case 'oklab':
    case 'oklch': {
      const L = scaled(t[0], 1, original);
      let a;
      let b;
      if (name === 'oklab') {
        a = scaled(t[1], 0.4, original);
        b = scaled(t[2], 0.4, original);
      } else {
        const C = scaled(t[1], 0.4, original);
        const H = (hue(t[2], original) * Math.PI) / 180;
        a = C * Math.cos(H);
        b = C * Math.sin(H);
      }
      return finishLinear(oklabToLinearSrgb(L, a, b), alpha);
    }
    default:
      throw new Error(`colour function "${name}()" is not supported for contrast checks`);
  }
}

/**
 * WCAG 2.x relative luminance of an opaque colour.
 * @param {{r: number, g: number, b: number}} c gamma-encoded sRGB channels 0..1
 */
export function relativeLuminance(c) {
  return 0.2126 * srgbToLinear(c.r) + 0.7152 * srgbToLinear(c.g) + 0.0722 * srgbToLinear(c.b);
}

/** Source-over compositing of `top` onto `under` in gamma-encoded sRGB (what browsers paint). */
export function compositeOver(top, under) {
  const a = top.a + under.a * (1 - top.a);
  if (a === 0) return { r: 0, g: 0, b: 0, a: 0 };
  const ch = (k) => (top[k] * top.a + under[k] * under.a * (1 - top.a)) / a;
  return { r: ch('r'), g: ch('g'), b: ch('b'), a };
}

const toColor = (c) => (typeof c === 'string' ? parseColor(c) : c);

/**
 * Unrounded WCAG contrast ratio (1..21). A translucent background is first painted over white;
 * a translucent foreground is then painted over the background.
 * @param {string|object} fg
 * @param {string|object} bg
 * @returns {number}
 */
export function contrastRatio(fg, bg) {
  let back = toColor(bg);
  if (back.a < 1) back = compositeOver(back, WHITE);
  let front = toColor(fg);
  if (front.a < 1) front = compositeOver(front, back);
  const l1 = relativeLuminance(front);
  const l2 = relativeLuminance(back);
  return (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
}

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

function resolveColorValue(ref, palette, theme) {
  if (Object.prototype.hasOwnProperty.call(palette, ref)) return palette[ref];
  const c = camel(ref);
  if (Object.prototype.hasOwnProperty.call(palette, c)) return palette[c];
  if (/^[a-z][a-zA-Z0-9-]*$/.test(ref) && !Object.prototype.hasOwnProperty.call(NAMED_COLORS, ref.toLowerCase())) {
    throw new Error(`"${ref}" is not a colour role in the ${theme} palette`);
  }
  return ref;
}

/**
 * Measure every contrastPairs entry. A pair without `theme` is checked in every palette the
 * preset defines. Roles are palette keys (camelCase or kebab-case); anything else must be a
 * colour value. `pass` uses the unrounded ratio; `ratio` is floored to 2 decimals for display,
 * so a reported 4.49 never hides a pass and a reported 4.5 never hides a fail.
 * @param {object} preset
 * @returns {object[]}
 */
export function checkContrastPairs(preset) {
  const results = [];
  const themes = ['light', 'dark'].filter((t) => preset?.color?.[t]);
  for (const pair of Array.isArray(preset?.contrastPairs) ? preset.contrastPairs : []) {
    for (const theme of pair.theme ? [pair.theme] : themes) {
      const base = { fg: pair.fg, bg: pair.bg, theme, min: pair.min };
      if (pair.note) base.note = pair.note;
      const palette = preset.color?.[theme];
      if (!palette) {
        results.push({ ...base, ratio: null, pass: false, error: `the preset has no ${theme} palette` });
        continue;
      }
      try {
        if (typeof pair.fg !== 'string' || typeof pair.bg !== 'string') throw new Error('fg and bg must be strings');
        if (typeof pair.min !== 'number' || !Number.isFinite(pair.min)) throw new Error('min must be a number');
        const fgValue = resolveColorValue(pair.fg, palette, theme);
        const bgValue = resolveColorValue(pair.bg, palette, theme);
        let bg = parseColor(bgValue);
        let fg = parseColor(fgValue);
        const translucent = bg.a < 1 || fg.a < 1;
        const outOfGamut = bg.outOfGamut || fg.outOfGamut;
        if (bg.a < 1) {
          let canvas = parseColor(palette.background);
          if (canvas.a < 1) canvas = compositeOver(canvas, theme === 'dark' ? BLACK : WHITE);
          bg = compositeOver(bg, canvas);
        }
        if (fg.a < 1) fg = compositeOver(fg, bg);
        const raw = contrastRatio(fg, bg);
        const result = { ...base, fgValue, bgValue, ratio: Math.floor(raw * 100) / 100, pass: raw >= pair.min };
        if (translucent) result.composited = 'translucent colour painted over the palette background';
        if (outOfGamut) result.clippedToSrgb = true;
        results.push(result);
      } catch (e) {
        results.push({ ...base, ratio: null, pass: false, error: e.message });
      }
    }
  }
  return results;
}

