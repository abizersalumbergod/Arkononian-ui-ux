let schemaCache = null;

/** Parsed schemas/preset.schema.json (cached). */
export function loadPresetSchema() {
  if (!schemaCache) {
    const text = readFileSync(SCHEMA_PATH, 'utf8');
    schemaCache = JSON.parse(text.charCodeAt(0) === 0xfeff ? text.slice(1) : text);
  }
  return schemaCache;
}

/**
 * Validate a preset object against schemas/preset.schema.json.
 * @param {object} preset
 * @returns {{valid: boolean, errors: string[]}}
 */
export function validatePreset(preset) {
  const result = validate(loadPresetSchema(), preset);
  return { valid: result.valid, errors: formatErrors(result.errors) };
}

/**
 * Resolve --preset: an existing path wins; otherwise a bare name maps to presets/<name>.json.
 * @param {string} value
 * @param {string} [cwd]
 * @returns {Promise<string>}
 */
export async function resolvePresetPath(value, cwd = process.cwd()) {
  const direct = path.resolve(cwd, value);
  if (await exists(direct)) return direct;
  if (/^[a-z0-9][a-z0-9-]*$/i.test(value)) {
    const bundled = path.join(PRESETS_DIR, `${value}.json`);
    if (await exists(bundled)) return bundled;
  }
  return direct;
}

const HELP = `Usage: node scripts/build-tokens.mjs --preset <file|name> [--out <dir> [--force] | --check] [--json]

Turns a design preset (see presets/README.md) into:
  tokens.css          :root custom properties (--font-*, --text-*, --leading-*, --tracking-*,
                      --radius-*, --spacing-*, --shadow-*, --duration-*, --ease-*); light colours
                      (--color-*) on :root and [data-theme="light"]; dark colours on
                      [data-theme="dark"] and under prefers-color-scheme: dark when the preset has
                      a dark palette; durations collapse to 0.01ms under prefers-reduced-motion.
  theme.tailwind.css  Tailwind CSS v4 @theme block with the same variable names (light values).
Every contrastPairs entry is measured with the WCAG 2.x formula; if any pair is below its
declared minimum (or cannot be measured) the build fails and nothing is written.

Options:
  --preset <file|name>  Preset JSON path, or a bundled preset name (presets/<name>.json).
  --out <dir>           Write tokens.css and theme.tailwind.css into <dir> (created if needed).
                        Existing files there are replaced only if build-tokens generated them.
  --force               With --out: also replace files that build-tokens did not generate.
  --check               Validate and measure contrast only; write nothing.
  --json                Print a JSON summary instead of text.
  -h, --help            Show this help.
Without --out or --check, both stylesheets are printed to stdout and the summary to stderr.

Exit codes:
  0   preset valid and every contrast pair meets its minimum
  1   a contrast pair is below its minimum or could not be measured
  3   invalid preset (unreadable, bad JSON, schema errors, unsafe token values)
  64  usage error (bad arguments, refusing to overwrite a file)
`;

function formatSummary(summary) {
  const lines = [`build-tokens: ${summary.name ?? '(unnamed)'} (${summary.preset})`];
  if (summary.errors?.length) lines.push('Errors:', ...summary.errors.map((e) => `  - ${e}`));
  if (summary.contrastResults?.length) {
    lines.push('Contrast (WCAG 2.x):');
    for (const r of summary.contrastResults) {
      const measured = r.ratio === null ? `not measured: ${r.error}` : `${r.ratio.toFixed(2)} ${r.pass ? '>=' : '<'} ${r.min}`;
      lines.push(`  ${r.pass ? 'PASS' : 'FAIL'}  ${r.theme.padEnd(5)}  ${`${r.fg} on ${r.bg}`.padEnd(34)} ${measured}`);
    }
  }
  if (summary.warnings?.length) lines.push('Warnings:', ...summary.warnings.map((w) => `  - ${w}`));
  if (summary.files?.length) lines.push('Wrote:', ...summary.files.map((f) => `  ${f}`));
  lines.push(`Result: ${summary.result}`);
  return `${lines.join('\n')}\n`;
}

/**
 * CLI entry point.
 * @param {string[]} argv
 * @returns {Promise<number>} exit code
 */
export async function main(argv) {
  let args;
  try {
    ({ values: args } = parseArgs({
      args: argv,
      options: {
        preset: { type: 'string' },
        out: { type: 'string' },
        force: { type: 'boolean', default: false },
        check: { type: 'boolean', default: false },
        json: { type: 'boolean', default: false },
        help: { type: 'boolean', short: 'h', default: false },
      },
      strict: true,
      allowPositionals: false,
    }));
  } catch (e) {
    process.stderr.write(`Error: ${e.message}\n\n${HELP}`);
    return EXIT.USAGE;
  }
  if (args.help) {
    process.stdout.write(HELP);
    return EXIT.OK;
  }
  if (!args.preset) {
    process.stderr.write(`Error: --preset <file|name> is required.\n\n${HELP}`);
    return EXIT.USAGE;
  }
  if (args.check && args.out) {
    process.stderr.write('Error: --check writes nothing; do not combine it with --out.\n');
    return EXIT.USAGE;
  }
  if (args.force && !args.out) {
    process.stderr.write('Error: --force only applies together with --out.\n');
    return EXIT.USAGE;
  }

  const presetPath = await resolvePresetPath(args.preset);
  const emit = (summary, toStderr = false) => {
    const text = args.json ? `${JSON.stringify(summary, null, 2)}\n` : formatSummary(summary);
    (toStderr ? process.stderr : process.stdout).write(text);
  };
  let preset;
  try {
    preset = await readJson(presetPath);
  } catch (e) {
    emit({ preset: presetPath, valid: false, result: 'INVALID', errors: [e.message] });
    return EXIT.INVALID;
  }
  const validation = validatePreset(preset);
  if (!validation.valid) {
    emit({ preset: presetPath, name: preset?.name, valid: false, result: 'INVALID (schema)', errors: validation.errors });
    return EXIT.INVALID;
  }
  let built;
  try {
    built = buildTokens(preset);
  } catch (e) {
    if (!(e instanceof TokenError)) throw e;
    emit({ preset: presetPath, name: preset.name, valid: false, result: 'INVALID (token values)', errors: [e.message] });
    return EXIT.INVALID;
  }
  const failed = built.contrastResults.filter((r) => !r.pass);
  const summary = {
    preset: presetPath,
    name: preset.name,
    valid: true,
    result: failed.length ? `FAIL (${failed.length} contrast pair(s) below minimum or not measurable; nothing written)` : 'OK',
    contrastResults: built.contrastResults,
    warnings: built.warnings,
    googleFontsUrl: built.googleFontsUrl,
    files: [],
  };
  const stdoutMode = !args.out && !args.check;
  if (failed.length) {
    emit(summary, stdoutMode && !args.json);
    return EXIT.CONTRAST;
  }
  if (args.check) {
    emit(summary);
    return EXIT.OK;
  }
  if (args.out) {
    const outDir = path.resolve(args.out);
    const st = await statOrNull(outDir);
    if (st && !st.isDirectory()) {
      process.stderr.write(`Error: --out must be a directory: ${outDir}\n`);
      return EXIT.USAGE;
    }
    const targets = [
      [path.join(outDir, OUTPUT_FILES.css), built.css],
      [path.join(outDir, OUTPUT_FILES.tailwind), built.tailwindTheme],
    ];
    for (const [file] of targets) {
      if (!args.force && (await exists(file))) {
        const head = (await readFile(file, 'utf8')).slice(0, 500);
        if (!head.includes(GENERATED_MARKER)) {
          process.stderr.write(`Error: refusing to overwrite ${file}: it was not generated by build-tokens (pass --force to replace it).\n`);
          return EXIT.USAGE;
        }
      }
    }
    for (const [file, content] of targets) await writeFileSafe(file, content, { force: true });
    summary.files = targets.map(([f]) => f);
    emit(summary);
    return EXIT.OK;
  }
  if (args.json) {
    process.stdout.write(`${JSON.stringify({ ...summary, css: built.css, tailwindTheme: built.tailwindTheme }, null, 2)}\n`);
  } else {
    process.stdout.write(`${built.css}\n/* ---- ${OUTPUT_FILES.tailwind} ---- */\n${built.tailwindTheme}`);
    emit(summary, true);
  }
  return EXIT.OK;
}

if (isMainModule(import.meta.url)) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (e) => {
      process.stderr.write(`Unexpected error: ${e?.stack ?? e}\n`);
      process.exitCode = EXIT.INVALID;
    },
  );
}
